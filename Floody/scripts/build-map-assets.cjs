const fs = require('node:fs');
const path = require('node:path');
const folder = path.resolve(__dirname, '../src/features/map/vendor');
const leafletRoot = path.dirname(require.resolve('leaflet/package.json'));
fs.mkdirSync(folder, { recursive: true });
const javascript = fs.readFileSync(path.join(leafletRoot, 'dist/leaflet.js'), 'utf8');
// Native markers are vector circles; remove unused CSS references to PNG controls.
const css = fs.readFileSync(path.join(leafletRoot, 'dist/leaflet.css'), 'utf8').replace(/url\([^)]*\)/g, 'none');
fs.writeFileSync(path.join(folder, 'leafletBundle.js'), '// Generated by npm run map:assets from the installed Leaflet package.\n// License: see Leaflet.LICENSE. Do not edit manually.\nexport const leafletJavaScript = ' + JSON.stringify(javascript) + ';\nexport const leafletCss = ' + JSON.stringify(css) + ';\n');
fs.copyFileSync(path.join(leafletRoot, 'LICENSE'), path.join(folder, 'Leaflet.LICENSE'));
console.log('Local Leaflet assets generated.');
